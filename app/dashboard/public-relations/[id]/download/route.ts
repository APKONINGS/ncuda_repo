import { getActor } from "@/lib/auth/actor";
import { recordAudit } from "@/lib/portal/audit";
import { committeeDocumentForDownload } from "@/lib/portal/committees";
import { getFileAsync } from "@/lib/portal/files";
import { getDocumentForDownload } from "@/lib/portal/queries";

/**
 * Permission-checked document download.
 *
 * Production: verify access exactly as below, then return a short-lived
 * Supabase Storage signed URL (created server-side) — never a public bucket
 * link. Demo: serves the uploaded bytes from memory, or a placeholder text
 * file for the seeded example documents.
 */
export async function GET(_req: Request, ctx: RouteContext<"/dashboard/public-relations/[id]/download">) {
  const actor = await getActor();
  if (!actor) return new Response("Sign in required.", { status: 401 });

  const { id } = await ctx.params;
  // Committee documents are seen only by the committee, its creator and the President General.
  const doc = getDocumentForDownload(actor, id) ?? committeeDocumentForDownload(actor, id);
  // Same response for "missing" and "not permitted": no information leaks.
  if (!doc) return new Response("Document not found.", { status: 404 });

  recordAudit(actor, {
    action: "DOWNLOAD",
    entityType: "document",
    entityId: doc.id,
    chapterId: doc.scope.level === "chapter" ? doc.scope.chapterId : null,
    regionId: doc.scope.level === "region" ? doc.scope.regionId : undefined,
    summary: `Downloaded “${doc.title}”`,
  });

  const stored = await getFileAsync(doc.id);
  if (stored) {
    return new Response(new Uint8Array(stored.bytes), {
      headers: {
        "content-type": stored.type,
        "content-disposition": `attachment; filename*=UTF-8''${encodeURIComponent(doc.filename)}`,
        "cache-control": "private, no-store",
        "x-content-type-options": "nosniff",
      },
    });
  }

  const body = [
    "NCUDA Member Portal — DEMONSTRATION FILE",
    "",
    `Title: ${doc.title}`,
    `Category: ${doc.category}`,
    "",
    "This is a placeholder generated by the demo. In production the real file is",
    "served from Supabase Storage through a short-lived signed URL after the same",
    "permission check that allowed this download.",
  ].join("\n");

  return new Response(body, {
    headers: {
      "content-type": "text/plain; charset=utf-8",
      "content-disposition": `attachment; filename="${doc.filename.replace(/\.pdf$/, "")}-demo.txt"`,
      "cache-control": "private, no-store",
    },
  });
}
